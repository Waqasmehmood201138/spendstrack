create or replace function public.create_group(p_name text, p_group_type public.group_type default 'other')
returns uuid language plpgsql security definer set search_path = public as $$
declare
  v_group_id uuid;
begin
  if auth.uid() is null then raise exception 'not authenticated'; end if;
  insert into public.groups (name, group_type, created_by) values (p_name, p_group_type, auth.uid()) returning id into v_group_id;
  insert into public.group_members (group_id, user_id, role) values (v_group_id, auth.uid(), 'owner');
  return v_group_id;
end;
$$;

create or replace function public.join_group_by_invite(p_invite_token uuid)
returns uuid language plpgsql security definer set search_path = public as $$
declare
  v_group_id uuid;
begin
  if auth.uid() is null then raise exception 'not authenticated'; end if;
  select id into v_group_id from public.groups where invite_token = p_invite_token and deleted_at is null;
  if v_group_id is null then raise exception 'invalid invite'; end if;
  insert into public.group_members (group_id, user_id, role) values (v_group_id, auth.uid(), 'member')
    on conflict (group_id, user_id) do nothing;
  return v_group_id;
end;
$$;

create or replace function public.add_friend_by_email(p_email text)
returns uuid language plpgsql security definer set search_path = public as $$
declare
  v_friend_id uuid;
begin
  if auth.uid() is null then raise exception 'not authenticated'; end if;
  select id into v_friend_id from public.profiles where lower(email) = lower(p_email);
  if v_friend_id is null then raise exception 'no user with that email'; end if;
  if v_friend_id = auth.uid() then raise exception 'cannot friend yourself'; end if;
  insert into public.friendships (user_id, friend_id) values (auth.uid(), v_friend_id) on conflict do nothing;
  insert into public.friendships (user_id, friend_id) values (v_friend_id, auth.uid()) on conflict do nothing;

  insert into public.notifications (user_id, type, actor_id, source_type, source_id, content)
  select v_friend_id, 'added_as_friend', auth.uid(), 'friendship', auth.uid(),
         (select first_name || ' ' || last_name from public.profiles where id = auth.uid()) || ' added you as a friend';

  return v_friend_id;
end;
$$;

create or replace function public.remove_friend(p_friend_id uuid)
returns void language plpgsql security definer set search_path = public as $$
begin
  if auth.uid() is null then raise exception 'not authenticated'; end if;
  delete from public.friendships where (user_id = auth.uid() and friend_id = p_friend_id)
                                     or (user_id = p_friend_id and friend_id = auth.uid());
end;
$$;

create or replace function public.add_group_member_by_email(p_group_id uuid, p_email text)
returns uuid language plpgsql security definer set search_path = public as $$
declare
  v_new_member_id uuid;
begin
  if not public.is_group_member(p_group_id, auth.uid()) then
    raise exception 'not authorized';
  end if;
  select id into v_new_member_id from public.profiles where lower(email) = lower(p_email);
  if v_new_member_id is null then raise exception 'no user with that email'; end if;
  insert into public.group_members (group_id, user_id) values (p_group_id, v_new_member_id)
    on conflict (group_id, user_id) do nothing;

  insert into public.notifications (user_id, type, actor_id, source_type, source_id, content)
  select v_new_member_id, 'added_to_group', auth.uid(), 'group', p_group_id,
         'You were added to ' || (select name from public.groups where id = p_group_id);

  return v_new_member_id;
end;
$$;

-- Fans notifications out to every other participant of an expense. A
-- narrow security-definer helper (rather than making create_expense() itself
-- definer) because `notifications` intentionally has no insert policy for
-- regular clients — nobody should be able to write an arbitrary
-- notification into another user's feed except through this controlled path.
create or replace function public.notify_expense_participants(p_expense_id uuid)
returns void language plpgsql security definer set search_path = public as $$
declare
  v_description text;
  v_is_payment  boolean;
  v_actor       uuid;
begin
  select description, is_payment, created_by into v_description, v_is_payment, v_actor
    from public.expenses where id = p_expense_id;

  insert into public.notifications (user_id, type, actor_id, source_type, source_id, content)
  select eu.user_id, 'expense_added', v_actor, 'expense', p_expense_id,
         (select first_name from public.profiles where id = v_actor) ||
         case when v_is_payment then ' recorded a payment: ' else ' added an expense: ' end || v_description
  from public.expense_users eu
  where eu.expense_id = p_expense_id and eu.user_id <> v_actor;
end;
$$;

-- Inserts a system-authored comment (user_id null). A narrow security-
-- definer helper for the same reason as notify_expense_participants:
-- comments_insert's RLS policy requires user_id = auth.uid(), which a NULL
-- (system) user_id can never satisfy — this is the one controlled path
-- allowed to write a system comment instead of relaxing that policy for
-- every client-side insert.
create or replace function public.add_system_comment(p_expense_id uuid, p_content text)
returns void language plpgsql security definer set search_path = public as $$
begin
  insert into public.comments (expense_id, comment_type, content) values (p_expense_id, 'system', p_content);
end;
$$;

-- p_users: [{ "user_id": uuid, "paid_share": numeric, "owed_share": numeric, "percentage": numeric|null, "shares": int|null }]
create or replace function public.create_expense(
  p_group_id        uuid,
  p_description     text,
  p_details         text,
  p_cost            numeric,
  p_currency_code   text,
  p_category_id     int,
  p_split_type      public.split_type,
  p_is_payment      boolean,
  p_expense_date     date,
  p_users            jsonb
) returns uuid language plpgsql security invoker set search_path = public as $$
declare
  -- Pre-generated rather than read back via `returning ... into`: this
  -- function is SECURITY INVOKER (RLS genuinely applies), and `returning`
  -- makes Postgres re-check the table's SELECT policy against the new row
  -- within the SAME command. expenses_select's can_access_expense() looks
  -- up this very row's group_id via a subquery on public.expenses — but a
  -- command's snapshot is fixed at its start, so that self-referential
  -- lookup can't see the row this same INSERT is still creating, and the
  -- check always fails ("new row violates row-level security policy").
  -- Knowing the id upfront avoids needing `returning` at all.
  v_expense_id uuid := gen_random_uuid();
begin
  insert into public.expenses (id, group_id, description, details, cost, currency_code, category_id, split_type, is_payment, expense_date, created_by)
  values (v_expense_id, p_group_id, p_description, p_details, p_cost, p_currency_code, p_category_id, p_split_type, p_is_payment, p_expense_date, auth.uid());

  insert into public.expense_users (expense_id, user_id, paid_share, owed_share, percentage, shares)
  select v_expense_id, (u ->> 'user_id')::uuid, (u ->> 'paid_share')::numeric, (u ->> 'owed_share')::numeric,
         (u ->> 'percentage')::numeric, (u ->> 'shares')::integer
  from jsonb_array_elements(p_users) as u;

  if not p_is_payment then
    perform public.add_system_comment(v_expense_id, 'created this expense');
  end if;

  perform public.notify_expense_participants(v_expense_id);

  return v_expense_id;
end;
$$;

create or replace function public.soft_delete_expense(p_expense_id uuid)
returns void language plpgsql security invoker set search_path = public as $$
begin
  if not public.can_access_expense(p_expense_id) then raise exception 'not authorized'; end if;
  update public.expenses set deleted_at = now(), deleted_by = auth.uid() where id = p_expense_id;
end;
$$;

