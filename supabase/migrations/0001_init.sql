-- ============================================================================
-- Balances (security_invoker so RLS on underlying tables still applies)
-- ============================================================================
create or replace view public.group_member_balances
with (security_invoker = true) as
select e.group_id, eu.user_id, e.currency_code, sum(eu.paid_share - eu.owed_share)::numeric(12, 2) as net_balance
from public.expense_users eu
join public.expenses e on e.id = eu.expense_id
where e.deleted_at is null and e.group_id is not null
group by e.group_id, eu.user_id, e.currency_code;

-- Pairwise friend balance: the *total* amount two people owe each other
-- across every expense they've ever shared, group or direct. Each ower's
-- owed_share is attributed across that expense's payers in proportion to how
-- much each payer actually paid — this generalizes correctly to both the
-- common single-payer case and multi-payer expenses. Deliberately not
-- filtered to group_id is null: a shared group expense contributes to the
-- friend balance exactly like a direct one, matching what Splitwise itself
-- shows on a friend's profile (their balance with you everywhere, not just
-- outside groups).
create or replace view public.friend_balances
with (security_invoker = true) as
with expense_totals as (
  select expense_id, sum(paid_share) as total_paid
  from public.expense_users
  group by expense_id
),
pairwise_debts as (
  select
    ower.user_id  as ower_id,
    payer.user_id as payer_id,
    e.currency_code,
    (ower.owed_share * payer.paid_share / nullif(et.total_paid, 0)) as amount
  from public.expense_users ower
  join public.expense_users payer
    on payer.expense_id = ower.expense_id and payer.user_id <> ower.user_id and payer.paid_share > 0
  join public.expenses e on e.id = ower.expense_id
  join expense_totals et on et.expense_id = ower.expense_id
  where e.deleted_at is null
),
directional as (
  select payer_id as viewer_id, ower_id as friend_id, currency_code, amount from pairwise_debts
  union all
  select ower_id as viewer_id, payer_id as friend_id, currency_code, -amount from pairwise_debts
)
select viewer_id, friend_id, currency_code, sum(amount)::numeric(12, 2) as net_balance
from directional
group by viewer_id, friend_id, currency_code;

