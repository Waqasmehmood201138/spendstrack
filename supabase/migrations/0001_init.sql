-- ============================================================================
-- table/view grants
-- ============================================================================
-- Enabling RLS on a table does NOT itself grant access — it only narrows
-- access a role already has. Without these, every query fails with
-- "permission denied for table X" (42501) regardless of how permissive the
-- RLS policies are, because the `authenticated` role never had base
-- SELECT/INSERT/UPDATE/DELETE privileges on these tables to begin with.
-- Each grant here matches exactly the operations a policy above allows for
-- that table — RLS remains the real, row-level security boundary.
grant select on public.currencies, public.categories to authenticated;
grant select, update on public.profiles to authenticated;
grant select, delete on public.friendships to authenticated;
grant select, update on public.groups to authenticated;
grant select, insert, delete on public.group_members to authenticated;
grant select, insert, update on public.expenses to authenticated;
grant select, insert on public.expense_users to authenticated;
grant select, insert, delete on public.comments to authenticated;
grant select, update on public.notifications to authenticated;
grant select on public.group_member_balances, public.friend_balances to authenticated;

-- ============================================================================
-- realtime
-- ============================================================================
-- Tables created outside the Supabase dashboard aren't added to the
-- `supabase_realtime` publication automatically — without this, every
-- `.stream()` call in the client fails with RealtimeSubscribeException
-- (channelError). Views (group_member_balances, friend_balances) are
-- deliberately NOT listed here: Postgres logical replication — what
-- Realtime is built on — only supports tables, so a view can never be
-- added to a publication. The client re-fetches those on demand instead
-- of streaming them; see lib/features/balances/data/balances_repository.dart.
alter publication supabase_realtime add table
  public.profiles,
  public.groups,
  public.group_members,
  public.expenses,
  public.comments,
  public.friendships,
  public.notifications;
