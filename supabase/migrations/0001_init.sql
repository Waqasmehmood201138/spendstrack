-- ============================================================================
-- SpendsTrack — initial schema
-- Mirrors the real Splitwise data model (see docs/database-schema.md):
--   - settlements are NOT a separate table. A "payment" is an expense row
--     with is_payment = true and exactly two expense_users rows.
--   - expense_users carries paid_share + owed_share per participant, which
--     natively supports multi-payer expenses with no extra modeling.
-- ============================================================================

