-- integrity: expense_users must sum to expense cost on both sides
create or replace function public.validate_expense_users_sum()
returns trigger language plpgsql as $$
declare
  v_expense_id uuid;
  v_cost       numeric;
  v_paid_sum   numeric;
  v_owed_sum   numeric;
begin
  for v_expense_id in select distinct expense_id from new_rows loop
    select cost into v_cost from public.expenses where id = v_expense_id;
    select coalesce(sum(paid_share), 0), coalesce(sum(owed_share), 0)
      into v_paid_sum, v_owed_sum
      from public.expense_users where expense_id = v_expense_id;
    if abs(v_paid_sum - v_cost) > 0.01 then
      raise exception 'expense_users.paid_share for expense % sums to % but cost is %', v_expense_id, v_paid_sum, v_cost;
    end if;
    if abs(v_owed_sum - v_cost) > 0.01 then
      raise exception 'expense_users.owed_share for expense % sums to % but cost is %', v_expense_id, v_owed_sum, v_cost;
    end if;
  end loop;
  return null;
end;
$$;
create trigger trg_validate_expense_users_sum
  after insert on public.expense_users
  referencing new table as new_rows
  for each statement execute function public.validate_expense_users_sum();

-- notify other expense participants when a user (not system) comments
create or replace function public.notify_comment_added()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if new.comment_type = 'user' then
    insert into public.notifications (user_id, type, actor_id, source_type, source_id, content)
    select eu.user_id, 'comment_added', new.user_id, 'expense', new.expense_id,
           (select first_name from public.profiles where id = new.user_id) || ' commented: ' || new.content
    from public.expense_users eu
    where eu.expense_id = new.expense_id and eu.user_id <> new.user_id;
  end if;
  return new;
end;
$$;
create trigger trg_notify_comment_added
  after insert on public.comments
  for each row execute function public.notify_comment_added();

-- RLS helper functions (SECURITY DEFINER to avoid self-referencing RLS recursion)
create or replace function public.is_group_member(_group_id uuid, _user_id uuid default auth.uid())
returns boolean language sql security definer set search_path = public stable as $$
  select exists (select 1 from public.group_members where group_id = _group_id and user_id = _user_id);
$$;

create or replace function public.is_expense_participant(_expense_id uuid, _user_id uuid default auth.uid())
returns boolean language sql security definer set search_path = public stable as $$
  select exists (select 1 from public.expense_users where expense_id = _expense_id and user_id = _user_id);
$$;

create or replace function public.can_access_expense(_expense_id uuid, _user_id uuid default auth.uid())
returns boolean language sql security definer set search_path = public stable as $$
  select case
    when (select group_id from public.expenses where id = _expense_id) is not null
      then public.is_group_member((select group_id from public.expenses where id = _expense_id), _user_id)
    else public.is_expense_participant(_expense_id, _user_id)
  end;
$$;

