-- ---------------------------------------------------------------------------
-- expenses (+ payments, via is_payment) and expense_users
-- ---------------------------------------------------------------------------
create table public.expenses (
  id              uuid primary key default gen_random_uuid(),
  group_id        uuid references public.groups (id) on delete cascade,   -- null = direct friend-to-friend expense
  description     text not null check (char_length(trim(description)) > 0),
  details         text,
  cost            numeric(12, 2) not null check (cost > 0),
  currency_code   text not null references public.currencies (code),
  category_id     int references public.categories (id),
  split_type      public.split_type not null default 'equal',
  is_payment      boolean not null default false,
  repeat_interval public.repeat_interval not null default 'never',
  expense_date    date not null default current_date,
  created_by      uuid not null references public.profiles (id),
  updated_by      uuid references public.profiles (id),
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now(),
  deleted_at      timestamptz,
  deleted_by      uuid references public.profiles (id)
);
create index expenses_group_id_date_idx on public.expenses (group_id, expense_date desc, created_at desc);
create index expenses_created_by_idx on public.expenses (created_by);
-- non-group (friend) expenses are looked up by participant via expense_users; no direct index needed here.

create table public.expense_users (
  expense_id  uuid not null references public.expenses (id) on delete cascade,
  user_id     uuid not null references public.profiles (id),
  paid_share  numeric(12, 2) not null default 0 check (paid_share >= 0),
  owed_share  numeric(12, 2) not null default 0 check (owed_share >= 0),
  percentage  numeric(5, 2) check (percentage is null or (percentage > 0 and percentage <= 100)),
  shares      integer check (shares is null or shares > 0),
  primary key (expense_id, user_id)
);
create index expense_users_user_id_idx on public.expense_users (user_id);

